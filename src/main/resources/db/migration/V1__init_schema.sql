-- Initial schema: users, tasks, labels, task_labels, notifications.
-- Column types, constraint and index names match the JPA entities (Hibernate runs with ddl-auto=validate).

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name          VARCHAR(100)             NOT NULL,
    email         VARCHAR(255)             NOT NULL,
    password_hash VARCHAR(100)             NOT NULL,
    role          VARCHAR(20)              NOT NULL,
    status        VARCHAR(20)              NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('USER')),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'BLOCKED'))
);

CREATE TABLE tasks (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    owner_id      BIGINT                   NOT NULL,
    title         VARCHAR(200)             NOT NULL,
    description   VARCHAR(2000),
    status        VARCHAR(20)              NOT NULL,
    deadline      TIMESTAMP(6) WITH TIME ZONE,
    completed_at  TIMESTAMP(6) WITH TIME ZONE,
    reminder_at   TIMESTAMP(6) WITH TIME ZONE,
    reminder_sent BOOLEAN                  NOT NULL,
    deleted_at    TIMESTAMP(6) WITH TIME ZONE,
    version       BIGINT                   NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_tasks PRIMARY KEY (id),
    CONSTRAINT fk_tasks_owner FOREIGN KEY (owner_id) REFERENCES users (id),
    CONSTRAINT ck_tasks_status CHECK (status IN ('TODO', 'IN_PROGRESS', 'BLOCKED', 'DONE'))
);

CREATE INDEX idx_tasks_owner_status ON tasks (owner_id, status);
CREATE INDEX idx_tasks_owner_deadline ON tasks (owner_id, deadline);
CREATE INDEX idx_tasks_reminder_at ON tasks (reminder_at);

CREATE TABLE labels (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    owner_id   BIGINT                   NOT NULL,
    name       VARCHAR(50)              NOT NULL,
    deleted_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_labels PRIMARY KEY (id),
    CONSTRAINT fk_labels_owner FOREIGN KEY (owner_id) REFERENCES users (id)
);

CREATE INDEX idx_labels_owner ON labels (owner_id);

CREATE TABLE task_labels (
    task_id  BIGINT NOT NULL,
    label_id BIGINT NOT NULL,
    CONSTRAINT pk_task_labels PRIMARY KEY (task_id, label_id),
    CONSTRAINT fk_task_labels_task FOREIGN KEY (task_id) REFERENCES tasks (id),
    CONSTRAINT fk_task_labels_label FOREIGN KEY (label_id) REFERENCES labels (id)
);

CREATE TABLE notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id    BIGINT                   NOT NULL,
    task_id    BIGINT                   NOT NULL,
    message    VARCHAR(500)             NOT NULL,
    read_at    TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_notifications PRIMARY KEY (id),
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_notifications_task FOREIGN KEY (task_id) REFERENCES tasks (id)
);

CREATE INDEX idx_notifications_user_read ON notifications (user_id, read_at);
